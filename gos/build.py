"""Build the GOS core and place it where Python and the Studio load it.

usage: py -3.12 gos/build.py     (needs Rust with the wasm32-unknown-unknown target)
The WebAssembly copy is embedded as text so the Studio builds and tests need no Rust toolchain.
"""
import base64, os, shutil, subprocess, sys
ROOT = os.path.dirname(os.path.abspath(__file__))
cargo = shutil.which('cargo') or shutil.which('cargo', path=os.path.expanduser(os.path.join('~', '.cargo', 'bin')))
if not cargo: sys.exit('Rust is not installed: get it from https://rustup.rs')
for args in ([], ['--target', 'wasm32-unknown-unknown']):
    subprocess.run([cargo, 'build', '--release', *args], cwd=ROOT, check=True)
wasm = open(os.path.join(ROOT, 'target', 'wasm32-unknown-unknown', 'release', 'gos_core.wasm'), 'rb').read()
out = os.path.join(ROOT, '..', 'studio', 'src', 'core', 'gos', 'gosCoreWasm.ts')
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by gos/build.py from gos/core. Do not edit.\nexport const GOS_CORE_WASM =\n  \'' + base64.b64encode(wasm).decode() + '\';\n')
names = {'win32': 'gos_core.dll', 'darwin': 'libgos_core.dylib'}
name = names.get(sys.platform, 'libgos_core.so')
lib = os.path.join(ROOT, 'python', 'gos', '_native')
os.makedirs(lib, exist_ok=True)
shutil.copy2(os.path.join(ROOT, 'target', 'release', name), os.path.join(lib, name))
print(f'wasm {len(wasm) // 1024} KB, native {name}')
